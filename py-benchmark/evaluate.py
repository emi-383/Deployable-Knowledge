import os
import json
import pathlib
from typing import Dict
from beir.datasets.data_loader import GenericDataLoader
from beir.retrieval.evaluation import EvaluateRetrieval
from data_load import DATASET_TYPE

SCRIPT_DIR = pathlib.Path(__file__).parent.absolute()
SYNC_FILE_PATH = os.path.join(SCRIPT_DIR, "active_dataset.txt")
DATA_DIR = os.path.join(SCRIPT_DIR, "data")
PRED_DIR = os.path.join(SCRIPT_DIR, "predictions")


def get_data():
    """Read transfer file from data_load.py, for DATASET_TYPE"""
    if not os.path.exists(SYNC_FILE_PATH):
        raise FileNotFoundError(
            f"[x] Sync file missing at {SYNC_FILE_PATH}."
            f"Please run data_load.py first to initialize the dataset."
        )
    
    with open(SYNC_FILE_PATH, "r", encoding="utf-8") as f:
        return f.read().strip()

def load_qrels(dataset_name: str) -> Dict[str, Dict[str, int]]:
    """Loads BEIR answer keys (qrels) for the given dataset"""
    dataset_path = os.path.join(DATA_DIR, dataset_name)

    if not os.path.exists(dataset_path):
        raise FileNotFoundError(f"[x] Dataset folder not found at {dataset_path}")
        
    print(f"Loading {dataset_name} test annotations---")
    # Returns corpus, queries, qrels
    # Only need qrels (the test labels)
    corpus, queries, qrels = GenericDataLoader(data_folder = dataset_path).load(split="test")
    ##
    return qrels

def evaluator(branch_name: str, qrels: Dict[str, Dict[str, int]], output):
    """Loads one retrieval branch and evaluates"""
    file_path = os.path.join(PRED_DIR, f"{branch_name}.json")

    if not os.path.exists(file_path):
        print(f"[x] Predictions for '{branch_name}' not found at {file_path}. Skipping.")
        return

    # Load output predictions generated by pipeline
    with open(file_path, "r", encoding="utf-8") as f:
        pred_results: Dict[str, Dict[str, float]] = json.load(f)
        # Cannot be 'results =', type-hinting is needed to load empty dict first

    results: Dict[str, Dict[str, float]] = {}
    for qid in qrels.keys():
        # If the RAG pipeline missed a query, provide an empty dict '{}'
        results[qid] = pred_results.get(qid, {})

    # Initialize BEIR evaluation class (pass None as model since we have precomputed results)
    retriever = EvaluateRetrieval(None, score_function="cos_sim")
    
    # Compute metrics
    ndcg, _map, recall, precision = retriever.evaluate(qrels, results, retriever.k_values)
    mrr = retriever.evaluate_custom(qrels, results, retriever.k_values, metric="mrr")
    
    print(f"\n================ {branch_name.upper()} RESULTS - {DATASET_TYPE} ================")
    print(f"NDCG@10:    {ndcg.get('NDCG@10', 0.0):.4f}")
    print(f"MAP@10:     {_map.get('MAP@10', 0.0):.4f}")
    print(f"MRR@10:     {mrr.get('MRR@10', 0.0):.4f}")
    print(f"Recall@100: {recall.get('Recall@100', 0.0):.4f}")

    output.write(f"\n================ {branch_name.upper()} results ================")
    output.write(f"\nNDCG@10:    {ndcg.get('NDCG@10', 0.0):.4f}")
    output.write(f"\nMAP@10:     {_map.get('MAP@10', 0.0):.4f}")
    output.write(f"\nMRR@10:     {mrr.get('MRR@10', 0.0):.4f}")
    output.write(f"\nRecall@100: {recall.get('Recall@100', 0.0):.4f}")


if __name__ == "__main__":
    active_dataset = get_data()
    qrels = load_qrels(active_dataset)

    script_dir = pathlib.Path(__file__).parent.absolute()

    output_file = open(f"{DATASET_TYPE}.txt", "w")
    output_file.write(f"{DATASET_TYPE} dataset: \n")
    
    target_branches = ["semantic", "bm25", "hybrid"]
    for branch in target_branches:
        evaluator(branch, qrels, output_file)

    output_file.close()
